function buildExtendedCommands(): VelocityCommand[] {
  const seen = new Set(BUILT_IN_EXISTING);
  const result: VelocityCommand[] = [];

  RAW_EXTENDED_SPECS.forEach(([name, category, description, usage, permission, cooldownSec], idx) => {
    const lower = name.toLowerCase();
    if (seen.has(lower)) return;
    seen.add(lower);

    const deterministicRuns = 45 + ((idx * 37 + lower.length * 19) % 420);
    result.push({
      id: `cmd-ext-${lower}`,
      name: lower,
      aliases: [],
      category,
      description,
      usage: usage || lower,
      examples: [usage ? usage.replace(/<[^>]+>/g, 'Velocity').replace(/\[[^\]]+\]/g, '').trim() : lower],
      permission: permission || 'Everyone',
      cooldownSec: cooldownSec ?? 3,
      enabled: true,
      executions: deterministicRuns,
      lastUsed: `${(idx % 55) + 2} mins ago`,
    });
  });

  return result;
}

export const EXTENDED_COMMANDS: VelocityCommand[] = buildExtendedCommands();
